#!/usr/bin/env node
// Generate the reviewer-facing LLM usage registry from src/lib/llm-registry.ts.
//
// The TypeScript registry is the source of truth used by runtime policy checks;
// this Markdown file is the stable audit surface for PR review and compliance
// handoff. `--check` fails when the committed document is stale.

import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

await import('./register-ts.mjs');

const { LLM_USAGE_REGISTRY, validateLlmUsageRegistry } = await import(
  '../src/lib/llm-registry.ts'
);

export const LLM_REGISTRY_DOC_PATH = fileURLToPath(
  new URL('../docs/llm-usage-registry.md', import.meta.url)
);

export function renderLlmUsageRegistryDoc(entries = LLM_USAGE_REGISTRY) {
  const lines = [
    '# LLM Usage Registry',
    '',
    '<!-- Generated by scripts/generate-llm-usage-registry-doc.mjs. Do not edit manually. -->',
    '',
    'This document is generated from `src/lib/llm-registry.ts` and checked by `npm run gate:llm-egress`. It lists every intentional Anthropic egress path, who pays for it, which credential class it may use, and which controls must stay in place before data can leave the dashboard.',
    '',
    '## Summary',
    '',
    '| ID | Surface | Rule | Credential | Data class | Egress scrub | Call site | Exposure |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  ];

  for (const entry of entries) {
    lines.push(
      [
        code(entry.id),
        entry.surface,
        entry.rule,
        entry.credential,
        entry.dataClass,
        entry.egressScrub,
        `${code(entry.callSite.file)}:${code(entry.callSite.symbol)}`,
        exposureSummary(entry.exposure),
      ]
        .map(tableCell)
        .join(' | ')
        .replace(/^/, '| ')
        .replace(/$/, ' |')
    );
  }

  lines.push(
    '',
    '## Pre-Public Exposure Gate',
    '',
    '`npm run gate:llm-egress` fails if any `publiclyReachable: true` registry entry lacks `authRequired=true`, complete call/input/spend caps, or an `egressScrub` mode other than `stub`.',
    '',
    'For a multi-tenant public deployment, run `DASHBOARD_LLM_PUBLIC_EXPOSURE_MODE=multi-tenant npm run gate:llm-egress`; in that mode every publicly reachable entry must also declare `tenancyBoundary=per-tenant`.',
    '',
    'The gate is necessary but not sufficient: the release-gate checklist still needs a named human sign-off that the reachable entries match the deployment being exposed.',
    '',
    '## Entry Details',
    ''
  );

  for (const entry of entries) {
    lines.push(
      `### ${code(entry.id)}`,
      '',
      `- Surface: ${code(entry.surface)}`,
      `- Rule: ${code(entry.rule)}`,
      `- Credential: ${code(entry.credential)}`,
      `- Purpose: ${entry.purpose}`,
      `- Trigger: ${code(entry.trigger)} - ${entry.triggerDescription}`,
      `- Data class: ${code(entry.dataClass)}`,
      `- Data boundary: ${entry.dataBoundary}`,
      `- Egress scrub: ${code(entry.egressScrub)}`,
      `- Call site: ${code(entry.callSite.file)} (${code(entry.callSite.symbol)})`,
      `- Exposure: ${exposureSummary(entry.exposure)}`,
      '',
      'Call budget:',
      ...bullets(entry.caps.callBudget),
      '',
      'Input bounds:',
      ...bullets(entry.caps.inputBounds),
      '',
      'Spend controls:',
      ...bullets(entry.caps.spendControls),
      '',
      'Required controls:',
      ...bullets(entry.requiredControls),
      ''
    );
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

export function expectedLlmUsageRegistryDoc() {
  const errors = validateLlmUsageRegistry();
  if (errors.length > 0) {
    throw new Error(
      `LLM usage registry is invalid:\n${errors.map((error) => `- ${error}`).join('\n')}`
    );
  }
  return renderLlmUsageRegistryDoc();
}

export function checkLlmUsageRegistryDocFresh() {
  const expected = expectedLlmUsageRegistryDoc();
  let actual = null;
  try {
    actual = readFileSync(LLM_REGISTRY_DOC_PATH, 'utf8');
  } catch (err) {
    return [
      `docs/llm-usage-registry.md is missing (${err.code ?? err.message})`,
    ];
  }
  if (actual !== expected) {
    return [
      'docs/llm-usage-registry.md is stale; run `node scripts/generate-llm-usage-registry-doc.mjs`.',
    ];
  }
  return [];
}

function writeDoc() {
  writeFileSync(LLM_REGISTRY_DOC_PATH, expectedLlmUsageRegistryDoc());
  console.log(`Wrote ${LLM_REGISTRY_DOC_PATH}`);
}

function checkDoc() {
  const errors = checkLlmUsageRegistryDocFresh();
  if (errors.length > 0) {
    for (const error of errors) console.error(error);
    process.exit(1);
  }
  console.log('LLM usage registry document is fresh.');
}

function code(value) {
  return `\`${String(value)}\``;
}

function bullets(items) {
  return items.map((item) => `- ${item}`);
}

function tableCell(value) {
  return String(value).replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');
}

function exposureSummary(exposure) {
  return [
    `whoPays=${exposure.whoPays}`,
    `authRequired=${exposure.authRequired}`,
    `tenancy=${exposure.tenancyBoundary}`,
    `public=${exposure.publiclyReachable}`,
  ].join(', ');
}

const invokedDirectly =
  process.argv[1] &&
  import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href;

if (invokedDirectly) {
  if (process.argv.includes('--check')) checkDoc();
  else writeDoc();
}
