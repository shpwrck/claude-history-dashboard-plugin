// SPA-upload ↔ server-ingest dataset parity gate (#2951).
//
// The free tier's correctness rests on the parsers being isomorphic: the
// server runs src/lib/parse-*.ts over the live ~/.claude tree
// (scripts/ingest.mjs → assembleDataset()), the SPA runs the IDENTICAL modules
// browser-side over an uploaded zip (buildUploadDataset). Until this test,
// nothing asserted the two paths actually produce equivalent datasets for the
// same input tree — the strongest untested product invariant the v0.6.0
// architecture survey found.
//
// Design: one fixture (the deterministic sample corpus that already drives the
// SPA demo build) is fed to BOTH pipelines from identical bytes — zipped for
// the upload path, written to a temp $HOME/.claude for the server path — and
// the datasets are compared over every shared key after applying the server's
// OWN declared wire-shaping (slimSessionTimeline, stripToolCommandBodies) and
// removing its provenance stamps (sourceId/harness). Every top-level key of
// assembleDataset()'s return must be classified below (parity, server-only, or
// fixture-empty); an unclassified new key fails the test, so the divergence
// allowlist is a reviewed boundary inventory like ENTERPRISE_ROUTE_INVENTORY.
//
// Run: node --import ./scripts/register-ts.mjs --test scripts/upload-server-parity.test.mjs

