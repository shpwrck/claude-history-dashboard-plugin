/**
 * Per-parity-key fields excluded from the row comparison because the two tiers
 * legitimately source them from tier-specific context (project/title
 * attribution), NOT from the shared parser output. The parsed CONTENT of every
 * row (token counts, tool calls, timeline shape, error codes, permission
 * rules) is still compared exactly — only these attribution stamps are
 * normalized away. Each is a documented, reviewed asymmetry; convergence is
 * tracked in the follow-up issue filed from #2951.
 */
export const FIELD_NORMALIZE = {
  // Server inlines the session title (deriveEntries, from the blob-cache
  // `title` column) onto every history entry; the upload transcript-entry
  // collector passes title=null (#978), so the SPA entry has no title. The
  // display/timestamp/project/sessionId — everything the entry MEANS — match.
  entries: ['title'],
  // The upload path passes the project decoded from the zip directory
  // (projects/<slug>/) into parseSessionJsonl; the server signal calls it with
  // no project arg and falls back to the transcript's own `cwd` (#1765), which
  // this synthetic corpus's turns don't carry. Every token/cache/context
  // COUNT is identical; only the derived project label + its short form differ.
  tokenData: ['project', 'projectShort'],
};

