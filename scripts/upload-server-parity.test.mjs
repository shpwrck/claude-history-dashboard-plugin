// ── Fixture plumbing ──────────────────────────────────────────────────────

function buildServerHome(corpus) {
  const home = join(tmpdir(), `chd-2951-home-${randomUUID()}`);
  const claude = join(home, '.claude');
  mkdirSync(claude, { recursive: true });
  writeFileSync(join(claude, 'history.jsonl'), corpus.historyJsonl);
  for (const s of corpus.sessions) {
    const proj = join(claude, 'projects', s.slug);
    mkdirSync(proj, { recursive: true });
    writeFileSync(join(proj, `${s.sessionId}.jsonl`), s.jsonl);
  }
  return home;
}

// Import ingest fresh with HOME + CHD_DB_PATH pointed at the fixture. Both are
// read at module load, so set them BEFORE the import; the cache-buster query
// keeps each import a distinct module instance (same recipe as
// transcript-cache-parity.test.mjs).
async function runServerPipeline(home) {
  const dbPath = join(tmpdir(), `chd-2951-db-${randomUUID()}.db`);
  const prevHome = process.env.HOME;
  const prevDb = process.env.CHD_DB_PATH;
  const prevClaudeDir = process.env.CLAUDE_DIR;
  process.env.HOME = home;
  process.env.CHD_DB_PATH = dbPath;
  delete process.env.CLAUDE_DIR;
  try {
    const mod = await import(`./ingest.mjs?parity=${randomUUID()}`);
    await mod.ingest();
    return { dataset: await mod.assembleDataset(), dbPath };
  } finally {
    process.env.HOME = prevHome;
    if (prevDb === undefined) delete process.env.CHD_DB_PATH;
    else process.env.CHD_DB_PATH = prevDb;
    if (prevClaudeDir !== undefined) process.env.CLAUDE_DIR = prevClaudeDir;
  }
}

// Run the REAL upload pipeline (inflate + 11 parse passes + collectors) over
// the zipped corpus and fold its emits exactly the way App.tsx applies them
// for a single fresh upload (no prior state, so replace-shaped dedup reduces
// to concatenation; permissions flatten into rows + changes; entries are
// history ∪ transcript with transcript winning by sessionId — via the real
// unionEntries).
async function runUploadPipeline(zipBytes) {
  const { buildUploadDataset } = await import('../src/lib/upload-dataset.ts');
  const { unionEntries } = await import('../src/lib/parse-history.ts');

  const folded = {
    entries: [],
    tokenData: [],
    toolData: [],
    toolInventories: [],
    timelines: [],
    apiErrors: [],
    permissionRows: [],
    permissionChanges: [],
    agentSettings: [],
    attribution: [],
    runtimeEvents: [],
    churnGeometry: [],
    valueFlow: [],
    memories: [],
    workflows: [],
    artifacts: null,
  };
  let historyEntries = [];
  let transcriptEntries = [];
  let transcriptSessionIds = [];

  const post = (msg) => {
    switch (msg.type) {
      case 'status':
      case 'sessionIndex':
        break;
      case 'history':
        historyEntries = historyEntries.concat(msg.entries);
        break;
      case 'transcriptEntries':
        transcriptEntries = transcriptEntries.concat(msg.entries);
        transcriptSessionIds = transcriptSessionIds.concat(msg.sessionIds);
        break;
      case 'tokens':
        folded.tokenData = folded.tokenData.concat(msg.data);
        break;
      case 'tools':
        folded.toolData = folded.toolData.concat(msg.data);
        break;
      case 'inventories':
        folded.toolInventories = folded.toolInventories.concat(msg.data);
        break;
      case 'timelines':
        folded.timelines = folded.timelines.concat(msg.data);
        break;
      case 'apiErrors':
        folded.apiErrors = folded.apiErrors.concat(msg.data);
        break;
      case 'permissions':
        folded.permissionRows = folded.permissionRows.concat(
          msg.data.flatMap((p) => p.perModeEntries)
        );
        folded.permissionChanges = folded.permissionChanges.concat(
          msg.data.flatMap((p) => p.changes)
        );
        break;
      case 'agentSettings':
        folded.agentSettings = folded.agentSettings.concat(msg.data);
        break;
      case 'attribution':
        folded.attribution = folded.attribution.concat(msg.data);
        break;
      case 'runtime':
        folded.runtimeEvents = folded.runtimeEvents.concat(msg.data);
        break;
      case 'churnGeometry':
        folded.churnGeometry = folded.churnGeometry.concat(msg.data);
        break;
      case 'valueFlow':
        folded.valueFlow = folded.valueFlow.concat(msg.data);
        break;
      case 'memories':
        folded.memories = msg.data;
        break;
      case 'workflows':
        folded.workflows = msg.data;
        break;
      case 'artifacts':
        folded.artifacts = msg.data;
        break;
      default:
        throw new Error(`unhandled upload emit type: ${msg.type}`);
    }
  };

  const summary = await buildUploadDataset(
    [{ blob: new Blob([zipBytes]), name: 'corpus.zip' }],
    post,
    { yielding: false }
  );
  folded.entries = unionEntries(historyEntries, transcriptEntries, transcriptSessionIds);
  return { folded, summary };
}

// ── Normalization: apply the server's DECLARED shaping to the SPA side and ──
// ── strip the server's provenance stamps, then sort both deterministically ──

// Provenance stamps the server adds to every value; always normalized away
// (multi-source addressing has no meaning for a single uploaded bundle).
const PROVENANCE_KEYS = ['sourceId', 'harness'];

function stripKeys(value, keys) {
  const drop = new Set([...PROVENANCE_KEYS, ...keys]);
  return JSON.parse(
    JSON.stringify(value, (key, v) => (drop.has(key) ? undefined : v))
  );
}

function sortRows(rows) {
  return [...rows]
    .map((r) => JSON.stringify(r))
    .sort()
    .map((s) => JSON.parse(s));
}

async function normalizeSides(key, spaRows, serverRows) {
  let spa = spaRows;
  if (key === 'timelines') {
    const { slimSessionTimeline } = await import('../src/lib/parse-timeline.ts');
    spa = spa.map((t) => slimSessionTimeline(t));
  }
  if (key === 'toolData') {
    const { stripToolCommandBodies } = await import('../src/lib/parse-tools.ts');
    spa = spa.map((t) => stripToolCommandBodies(t));
  }
  const fieldDrops = FIELD_NORMALIZE[key] ?? [];
  return {
    spa: sortRows(stripKeys(spa, fieldDrops)),
    server: sortRows(stripKeys(serverRows, fieldDrops)),
  };
}

// ── The gate ──────────────────────────────────────────────────────────────

test('SPA upload parse and server ingest agree over the same ~/.claude tree (#2951)', async () => {
  const corpus = buildSampleCorpus();
  // Exercise the history∪transcript UNION fallback: a session that appears in
  // history.jsonl with NO transcript file. Every sample session has a
  // transcript, so without this the "keep the history entry for a
  // transcript-less session" branch — of both unionEntries (SPA) and the
  // server's `!transcriptSessionIds.has(...)` filter — never fires, and the
  // parity claim over `entries` would silently miss a real divergence there.
  // corpus.historyJsonl feeds BOTH sides (buildServerHome + corpusZipEntries),
  // so appending one line covers both.
  const historyOnly = {
    display: 'A prompt whose session left no transcript on disk.',
    pastedContents: {},
    timestamp: 1_779_000_000_000,
    project: '-home-dev-acme-web',
    sessionId: '20260517-9999-history-only-sample',
  };
  corpus.historyJsonl += JSON.stringify(historyOnly) + '\n';

  const zipBytes = zipSync(corpusZipEntries(corpus), {
    level: 0,
    mtime: new Date('2026-01-01T00:00:00Z'),
  });
  const home = buildServerHome(corpus);
  let dbPath;
  try {
    const server = await runServerPipeline(home);
    dbPath = server.dbPath;
    const { folded, summary } = await runUploadPipeline(zipBytes);
    assert.ok(summary.usableFiles > 0, 'upload pipeline found no usable files');

    // The union fallback is actually exercised: the transcript-less session's
    // history entry survives on BOTH sides (if either dropped it, the entries
    // deep-equal below would fail; this asserts the branch ran at all).
    const historyOnlyId = '20260517-9999-history-only-sample';
    assert.ok(
      folded.entries.some((e) => e.sessionId === historyOnlyId),
      'SPA union dropped the transcript-less history entry — fallback branch not exercised'
    );
    assert.ok(
      (server.dataset.entries ?? []).some((e) => e.sessionId === historyOnlyId),
      'server union dropped the transcript-less history entry — fallback branch not exercised'
    );

    // 1) Full classification: every server dataset key is exactly one of
    //    parity / server-only / fixture-empty. A new assembleDataset() key
    //    fails here until it is consciously classified.
    const serverKeys = Object.keys(server.dataset);
    const classified = new Set([
      ...PARITY_KEYS,
      ...Object.keys(SERVER_ONLY_KEYS),
      ...FIXTURE_EMPTY_KEYS,
    ]);
    const unclassified = serverKeys.filter((k) => !classified.has(k));
    assert.deepEqual(
      unclassified,
      [],
      `assembleDataset() keys not classified in the #2951 parity inventory: ${unclassified.join(', ')} — add each to PARITY_KEYS, SERVER_ONLY_KEYS (with a reason), or FIXTURE_EMPTY_KEYS`
    );
    // Keys spread into the return object only when their opt-in flag or data
    // source exists (the flag-off byte-identical rule): absent here is fine,
    // but when present they are already classified above.
    const CONDITIONAL_KEYS = new Set([
      'gitOutcomes',
      'docIssueSnapshot',
      'localCalibration',
      'recommendations',
      'memories',
    ]);
    const phantom = [...classified].filter(
      (k) => !serverKeys.includes(k) && !CONDITIONAL_KEYS.has(k)
    );
    assert.deepEqual(
      phantom,
      [],
      `classified keys no longer returned by assembleDataset(): ${phantom.join(', ')}`
    );

    // 2) Parity keys: deep-equal after declared shaping + provenance strip.
    for (const key of PARITY_KEYS) {
      const spaRows = folded[key];
      const serverRows = server.dataset[key] ?? [];
      const { spa, server: srv } = await normalizeSides(key, spaRows, serverRows);
      assert.equal(
        spa.length,
        srv.length,
        `${key}: SPA produced ${spa.length} row(s), server ${srv.length}`
      );
      assert.deepEqual(
        spa,
        srv,
        `${key}: SPA and server rows diverge after declared normalization`
      );
    }

    // 3) Fixture-empty keys: both sides yield nothing for this fixture, so a
    //    server-side source of any of these NOT visible to the upload path
    //    would surface here as an asymmetry.
    for (const key of FIXTURE_EMPTY_KEYS) {
      const serverVal = server.dataset[key];
      const emptyServer =
        serverVal == null ||
        (Array.isArray(serverVal) && serverVal.length === 0) ||
        (typeof serverVal === 'object' && Object.keys(serverVal).length === 0);
      assert.ok(
        emptyServer,
        `${key}: expected empty from the transcripts+history fixture, server produced ${JSON.stringify(serverVal)?.slice(0, 200)}`
      );
    }
  } finally {
    rmSync(home, { recursive: true, force: true });
    // Remove the throwaway SQLite db and its node:sqlite -wal/-shm sidecars.
    if (dbPath) {
      for (const suffix of ['', '-wal', '-shm']) {
        rmSync(`${dbPath}${suffix}`, { force: true });
      }
    }
  }
});
