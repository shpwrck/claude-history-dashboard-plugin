#!/usr/bin/env node
// Backfill an existing GitHub Release body into the repo's release-notes shape
// (#716): a hand-written summary on top, then the changelog regrouped under the
// .github/release.yml categories using the merged PRs' labels.
//
// v0.1.1 and v0.2.0 were published as flat `--generate-notes` dumps (no summary,
// effectively all-"Other" because the PRs were unlabeled). Editing a published
// Release body needs the REST API; this script regenerates the body as:
//
//   1. The existing hand-written summary if the body has one — preserved
//      verbatim. Otherwise a PLACEHOLDER the maintainer must replace (the run
//      emits a loud notice; drafted paragraphs live in
//      docs/release-notes-backfill.md).
//   2. "## What's Changed" with the body's existing PR bullet lines regrouped
//      under the release.yml categories by each PR's CURRENT labels — so run
//      the labeling helper first (scripts/label-milestone-prs.mjs / the
//      "Label milestone PRs" workflow), or everything stays in "Other changes".
//   3. The "## New Contributors" / "**Full Changelog**" tail, preserved.
//
// It NEVER destroys an existing body: the previous body is kept verbatim under
// an HTML-comment marker at the bottom of the new body AND printed in the run
// log. On a re-run the CURRENT body is re-preserved (prior block stripped)
// (no nesting).
//
// DRY-RUN BY DEFAULT: prints the composed body and exits. Pass --apply to PATCH
// the Release.
//
// Usage:
//   node scripts/backfill-release-notes.mjs <tag> [--apply]
// Env: GH_TOKEN (or GITHUB_TOKEN) — a token with contents:write;
//      GH_REPO (or GITHUB_REPOSITORY) — owner/repo.
// CI: .github/workflows/backfill-release-notes.yml (workflow_dispatch).
//
// Pure regrouping/composition logic is exported and unit-tested with fixture PR
// lists (scripts/backfill-release-notes.test.mjs, mocked fetch);
// `npm run test:backfill-release-notes`.

import { realpathSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { ghApi, loadReleaseConfig } from './label-milestone-prs.mjs';

// NOTE: the marker text must never contain the HTML comment terminator.
export const PRESERVED_MARKER = 'backfill-release-notes: original body preserved below (verbatim; comment terminators escaped); do not edit';

export const PLACEHOLDER_SUMMARY = [
  '<!-- TODO(maintainer): replace the line below with a 2-4 sentence hand-written',
  'summary. Drafted paragraphs live in docs/release-notes-backfill.md. -->',
  '_Summary pending — see docs/release-notes-backfill.md for the drafted paragraph for this release._',
].join('\n');

function escapeRegExpEarly(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
const PRESERVED_BLOCK_RE = new RegExp(
  `<!--\\s*${escapeRegExpEarly(PRESERVED_MARKER)}[\\s\\S]*?-->`
);

/** Remove a previous run's preserved-body block, so blocks never nest. */
export function stripPreservedBlock(body) {
  return String(body ?? '').replace(PRESERVED_BLOCK_RE, '').trim();
}

const CHANGED_HEADING = /^##\s+What['’]?s Changed\s*$/i;
const TAIL_HEADING = /^(##\s+New Contributors\s*$|\*\*Full Changelog\*\*)/i;
const PR_BULLET = /^\*\s+.*\/pull\/(\d+)\s*$/;

// Split a Release body into:
//   summary   — prose above "## What's Changed" (existing hand-written summary,
//               or '' when the body starts at the changelog)
//   entries   — [{ number, line }] for every PR bullet in the changelog region
//               (### category subheadings are dropped; regrouping recreates them)
//   tail      — "## New Contributors" section + "**Full Changelog**" line onward
//   preserved — a previously-preserved original-body block (marker comment), if
//               this body was already produced by a backfill run
export function splitReleaseBody(body) {
  let text = String(body ?? '').replace(/\r\n/g, '\n');

  let preserved = null;
  const markerMatch = text.match(PRESERVED_BLOCK_RE);
  if (markerMatch) {
    preserved = markerMatch[0];
    text = text.replace(PRESERVED_BLOCK_RE, '');
  }

  const lines = text.split('\n');
  const changedAt = lines.findIndex((l) => CHANGED_HEADING.test(l.trim()));

  // No changelog heading: the whole body is prose — keep it as the summary
  // rather than dropping it.
  const summaryLines = changedAt === -1 ? lines : lines.slice(0, changedAt);
  const rest = changedAt === -1 ? [] : lines.slice(changedAt + 1);

  const entries = [];
  const tailLines = [];
  let inTail = false;
  for (const line of rest) {
    if (!inTail && TAIL_HEADING.test(line.trim())) inTail = true;
    if (inTail) {
      tailLines.push(line);
      continue;
    }
    const bullet = line.match(PR_BULLET);
    if (bullet) entries.push({ number: Number(bullet[1]), line: line.trimEnd() });
    // Anything else in the changelog region (### subheadings, blank lines) is
    // regenerated by the regrouping, so it is intentionally dropped here.
  }

  return {
    summary: summaryLines.join('\n').trim(),
    entries,
    tail: tailLines.join('\n').trim(),
    preserved,
  };
}

// Regroup changelog entries (each carrying its PR's labels) under the
// release.yml categories: first matching category in config order wins (the
// `*` catch-all matches anything), mirroring GitHub's own bucketing. Entries
// whose labels hit the exclude list are dropped (and reported).
export function regroupChangelog(entries, config) {
  const sections = config.categories.map((c) => ({ title: c.title, lines: [] }));
  const excluded = [];
  for (const e of entries) {
    const labels = e.labels || [];
    if (labels.some((l) => config.exclude.includes(l))) {
      excluded.push(e);
      continue;
    }
    const idx = config.categories.findIndex(
      (c) => c.labels.includes('*') || c.labels.some((l) => labels.includes(l)),
    );
    const target = idx >= 0 ? sections[idx] : sections[sections.length - 1];
    target.lines.push(e.line);
  }
  return { sections: sections.filter((s) => s.lines.length > 0), excluded };
}

// An HTML comment ends at the first "-->", so that sequence in the preserved
// body is escaped as "--\>" (the run log always prints the verbatim original).
export function preserveBody(originalBody) {
  const escaped = String(originalBody ?? '').replace(/-->/g, '--\\>');
  return `<!-- ${PRESERVED_MARKER}\n${escaped}\n-->`;
}

// Compose the new Release body. The marker block always re-preserves the
// CURRENT pre-run body (with any previous run's block stripped so blocks
// never nest): post-backfill hand edits survive in the new marker instead of
// existing only in the prior run's Actions log. A summary that is ONLY the
// placeholder stays flagged as a placeholder; prose the maintainer wrote
// around a not-yet-deleted placeholder line is kept (placeholder scaffolding
// stripped), never clobbered back to the bare placeholder.
export function composeBody({ summary, sections, tail, originalBody }) {
  const parts = [];
  const prose = String(summary ?? '')
    .replace(PLACEHOLDER_SUMMARY, '')
    .replace(/<!--\s*TODO\(maintainer\)[\s\S]*?-->/g, '')
    .replace(/^.*_Summary pending —.*$/gm, '')
    .trim();
  const usedPlaceholder = !prose;
  parts.push(usedPlaceholder ? PLACEHOLDER_SUMMARY : prose);
  parts.push('## What\'s Changed');
  for (const s of sections) {
    parts.push(`### ${s.title}`);
    parts.push(s.lines.join('\n'));
  }
  if (tail && tail.trim()) parts.push(tail.trim());
  parts.push(preserveBody(stripPreservedBlock(originalBody)));
  return { body: parts.join('\n\n'), usedPlaceholder };
}

// ---------------------------------------------------------------------------
// Orchestration (network via injected fetch; exercised by the test with mocks).
// ---------------------------------------------------------------------------

export async function backfillReleaseNotes({
  repo,
  tag,
  token,
  fetchImpl = globalThis.fetch,
  apply = false,
  config = loadReleaseConfig(),
  log = console.log,
}) {
  const opts = { token, fetchImpl };

  const release = await ghApi(`/repos/${repo}/releases/tags/${encodeURIComponent(tag)}`, opts);
  const originalBody = release.body ?? '';

  const { summary, entries, tail } = splitReleaseBody(originalBody);
  if (entries.length === 0) {
    throw new Error(
      `release ${tag} has no PR bullet lines ("* ... /pull/N") in its body — nothing to regroup. ` +
      'If the release has no generated notes yet, regenerate them first (gh release create --generate-notes).',
    );
  }

  // Each PR's CURRENT labels drive the regrouping — run the labeling helper
  // first so this is not all-"Other".
  const withLabels = [];
  for (const e of entries) {
    let labels = [];
    try {
      const issue = await ghApi(`/repos/${repo}/issues/${e.number}`, opts);
      labels = (issue.labels || []).map((l) => (typeof l === 'string' ? l : l?.name)).filter(Boolean);
    } catch (err) {
      log(`  ! could not read labels of PR #${e.number}: ${err.message} — treating as unlabeled`);
    }
    withLabels.push({ ...e, labels });
  }

  const { sections, excluded } = regroupChangelog(withLabels, config);
  const { body, usedPlaceholder } = composeBody({ summary, sections, tail, originalBody });

  if (apply) {
    await ghApi(`/repos/${repo}/releases/${release.id}`, {
      ...opts,
      method: 'PATCH',
      body: { body },
    });
  }

  return {
    release: { id: release.id, tag },
    body,
    usedPlaceholder,
    sections: sections.map((s) => ({ title: s.title, count: s.lines.length })),
    excluded,
    originalBody,
    applied: apply,
  };
}

// ---------------------------------------------------------------------------
// CLI.
// ---------------------------------------------------------------------------

function fail(msg) {
  console.error(`\n::error::${msg}`);
  process.exit(1);
}

async function main() {
  const args = process.argv.slice(2);
  const apply = args.includes('--apply');
  const tag = args.find((a) => !a.startsWith('--'));
  if (!tag || !/^v\d+\.\d+\.\d+$/.test(tag)) {
    fail('Usage: node scripts/backfill-release-notes.mjs <vX.Y.Z> [--apply]');
    return;
  }
  const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
  if (!token) {
    fail('Set GH_TOKEN (or GITHUB_TOKEN) to a token with contents:write.');
    return;
  }
  const repo = process.env.GH_REPO || process.env.GITHUB_REPOSITORY;
  if (!repo) {
    fail('Set GH_REPO (or GITHUB_REPOSITORY) to owner/repo.');
    return;
  }

  let result;
  try {
    result = await backfillReleaseNotes({ repo, tag, token, apply });
  } catch (err) {
    fail(err.message);
    return;
  }

  // The previous body always lands in the run log, in addition to the
  // marker-comment copy inside the new body itself.
  console.log(`\n--- previous body of ${tag} (verbatim) ---\n${result.originalBody}\n--- end previous body ---\n`);

  console.log(`Regrouped ${tag}:`);
  for (const s of result.sections) console.log(`  ${s.title}: ${s.count} PR(s)`);
  if (result.excluded.length > 0) {
    console.log(`  excluded (release.yml exclude labels): ${result.excluded.map((e) => `#${e.number}`).join(', ')}`);
  }
  if (result.sections.length === 1 && result.sections[0].title === 'Other changes') {
    console.log('\n::warning::Everything regrouped into "Other changes" — the merged PRs are unlabeled. Run the "Label milestone PRs" workflow first, then re-run this one.');
  }

  console.log(`\n--- composed body of ${tag} ---\n${result.body}\n--- end composed body ---\n`);

  if (result.usedPlaceholder) {
    console.log(`::warning::Release ${tag} has NO hand-written summary — a placeholder was inserted. Replace it with the drafted paragraph from docs/release-notes-backfill.md (edit the release body, or paste the draft above "## What's Changed" and re-run).`);
  }

  if (result.applied) {
    console.log(`✓ Release ${tag} body updated.`);
  } else {
    console.log(`Dry run — release ${tag} was NOT modified. Re-run with --apply to write the body above.`);
  }
}

const invokedDirectly =
  process.argv[1] &&
  import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href;
if (invokedDirectly) await main();
